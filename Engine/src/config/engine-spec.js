/**
 * @file Параметры двигателя для чистой математики Engine (слой config).
 *
 * D-05 (утверждён 2 ноября 2026 г., вариант A): единая спецификация A «85 × 72» — геометрия 3D-модели.
 * Первичные размеры заданы в мм, параметры сцены в u выводятся из них; рабочий объём и объём камеры
 * сгорания считаются из той же геометрии. Значения в u побитно равны литералам Engine/Engine.html.
 * Модуль ничего не импортирует: без Three.js, без DOM, без изменяемого состояния (массивы заморожены).
 * Engine.html эти модули пока не использует (M-01b); его копии констант сверяет Engine/tests/spec-sync.test.js.
 *
 * Единицы
 *   u    — мировая единица 3D-сцены. 1 ед. = 100 мм (соглашение модели) — U_MM; Engine.html:422.
 *          Пример: BORE_R = 0.425 u ↔ Ø 85 мм.
 *   мм   — миллиметры, см³ — кубические сантиметры.
 *   °    — градусы угла коленвала. φ — фаза цилиндра в 720-градусном цикле, φ = 0 — ВМТ в начале рабочего хода.
 *   рад  — радианы.
 *
 * Спецификация A — учебная модель, а не паспорт конкретного двигателя: внешнего инженерного источника нет.
 * Источник значений — решение D-05 и код Engine/Engine.html (номера строк у параметров).
 * Отклонённая альтернатива B «86 × 86» (Ø 86 × 86 мм, 1998 см³, кривошип 43 мм, шатун 144 мм,
 * компрессионная высота 30 мм, подъём клапана 9,6 мм) до D-05 была в карточках, показаниях и модели p–V
 * Engine.html. В коде её значений больше нет; упоминание здесь — только для истории решения.
 *
 * Ограничение (D-05, решение 7). Степень сжатия CR = 10,5 — параметр термодинамической модели (L2),
 * 3D-геометрия её не подтверждает. В ВМТ днище поршня — на PIN_TDC + PIN_TOP = 2,39 u, низ ГБЦ —
 * на HEAD_BOT = 2,48 u (Engine.html:431): зазор 0,09 u = 9 мм, камеры сгорания в 3D нет.
 * Плоская камера Ø 85 мм высотой 9 мм дала бы VC ≈ 51,1 см³ и CR ≈ 9,0. 3D-геометрия по D-05 не меняется.
 *
 * У каждого параметра указаны: смысл · единицы · источник · группа.
 */

/**
 * Перевод градусов в радианы: π / 180.
 * Единицы: рад/°. Источник: Engine.html:447. Группа: математическая константа.
 */
export const DEG = Math.PI / 180;

/**
 * Масштаб 3D-сцены: миллиметров в одной мировой единице. 1 ед. = 100 мм — соглашение модели,
 * а не измерение (D-05, решение 6).
 * Единицы: мм/u. Источник: D-05; Engine.html:422. Группа: соглашение модели.
 */
export const U_MM = 100;

// ---------- Спецификация A: первичные размеры, мм ----------

/**
 * Число цилиндров, рядная компоновка.
 * Единицы: шт. Источник: D-05; Engine.html:424 (четыре оси CYL_X). Группа: A.
 */
export const CYLINDERS = 4;

/**
 * Диаметр цилиндра D.
 * Единицы: мм. Источник: D-05; Engine.html:429 (BORE_R = 0.425 u). Группа: A.
 */
export const BORE_MM = 85;

/**
 * Ход поршня S = 2 · радиус кривошипа.
 * Единицы: мм. Источник: D-05; Engine.html:427 (CRANK_R = 0.36 u). Группа: A.
 */
export const STROKE_MM = 72;

/**
 * Длина шатуна между осями головок L.
 * Единицы: мм. Источник: D-05; Engine.html:427 (ROD_L = 1.25 u). Группа: A.
 */
export const ROD_MM = 125;

/**
 * Компрессионная высота поршня: от оси поршневого пальца до днища.
 * Единицы: мм. Источник: D-05; Engine.html:428 (PIN_TOP = 0.23 u). Группа: A.
 */
export const COMPRESSION_HEIGHT_MM = 23;

/**
 * Наибольший подъём клапана (он же наибольший подъём кулачка).
 * Единицы: мм. Источник: D-05; Engine.html:434 (CAM_LIFT = 0.092 u). Группа: A.
 */
export const VALVE_LIFT_MM = 9.2;

/**
 * Степень сжатия (VS + VC) / VC. Параметр модели давления L2: 3D-геометрия её не подтверждает
 * (зазор в ВМТ 9 мм ≈ 9,0 : 1 для плоской камеры, см. шапку файла).
 * Единицы: безразмерная. Источник: D-05 (решение 7); Engine.html:533 (карточка «10,5 : 1»). Группа: A, модель давления.
 */
export const CR = 10.5;

// ---------- Спецификация A: геометрия 3D-модели, u (выводится из мм) ----------

/**
 * Высота оси коленвала — координата Y сцены (положение, а не размер двигателя).
 * Единицы: u. Источник: Engine.html:427. Группа: A, 3D-сцена.
 */
export const CRANK_Y = 0.55;

/**
 * Радиус кривошипа R = S / 2: 0,36 u = 36 мм. Побитно равно литералу 0.36 (Engine.html:427).
 * Единицы: u. Источник: STROKE_MM, U_MM; Engine.html:427. Группа: A.
 */
export const CRANK_R = STROKE_MM / 2 / U_MM;

/**
 * Длина шатуна: 1,25 u = 125 мм. Побитно равно литералу 1.25 (Engine.html:427).
 * Единицы: u. Источник: ROD_MM, U_MM; Engine.html:427. Группа: A.
 */
export const ROD_L = ROD_MM / U_MM;

/**
 * Радиус цилиндра D / 2: 0,425 u = 42,5 мм. Побитно равно литералу 0.425 (Engine.html:429).
 * Единицы: u. Источник: BORE_MM, U_MM; Engine.html:429. Группа: A.
 */
export const BORE_R = BORE_MM / 2 / U_MM;

/**
 * Компрессионная высота в единицах сцены: 0,23 u = 23 мм. Побитно равно литералу 0.23 (Engine.html:428).
 * Функции Engine/src её не используют.
 * Единицы: u. Источник: COMPRESSION_HEIGHT_MM, U_MM; Engine.html:428. Группа: A.
 */
export const PIN_TOP = COMPRESSION_HEIGHT_MM / U_MM;

/**
 * Наклон оси клапана к оси цилиндра; впускные и выпускные клапаны наклонены в разные стороны.
 * 12 * DEG побитно равно legacy-выражению THREE.MathUtils.degToRad(12)
 * (three r160: degrees * DEG2RAD, DEG2RAD = Math.PI / 180).
 * Единицы: рад. Источник: Engine.html:432. Группа: A.
 */
export const VALVE_TILT = 12 * DEG;

/**
 * Наибольший подъём кулачка, он же ход клапана (клапан смещается на подъём вдоль своей оси,
 * Engine.html:1409): 0,092 u = 9,2 мм. Побитно равно литералу 0.092 (Engine.html:434).
 * Единицы: u. Источник: VALVE_LIFT_MM, U_MM; Engine.html:434. Группа: A.
 */
export const CAM_LIFT = VALVE_LIFT_MM / U_MM;

// ---------- Фазы и углы: общие для 3D-анимации, p–V и показаний ----------

/**
 * Угол коленвала в 720-градусном цикле, при котором цилиндр с индексом i (0…3) находится в ВМТ такта
 * сжатия — момент искры без учёта опережения. Порядок работы 1-3-4-2. Фаза цилиндра φi = θ° − FIRE_DEG[i].
 * Единицы: ° коленвала. Источник: Engine.html:425–426. Группа: фазы.
 */
export const FIRE_DEG = Object.freeze([0, 540, 180, 360]);

/**
 * Полуширина профиля кулачка по углу распредвала: 58°. Клапан открыт 2 × 58° = 116° распредвала,
 * то есть 232° коленвала. 58 * DEG побитно равно legacy-выражению THREE.MathUtils.degToRad(58).
 * Единицы: рад (угол распредвала). Источник: Engine.html:438. Группа: фазы.
 */
export const CAM_HALF = 58 * DEG;

/**
 * Фаза середины открытия впускного клапана. Впуск открыт при φ 349…581°, то есть
 * 11° до ВМТ … 41° после НМТ — как в карточке Engine.html:547.
 * Единицы: ° фазы φ. Источник: Engine.html:439. Группа: фазы.
 */
export const IN_MID = 465;

/**
 * Фаза середины открытия выпускного клапана. Выпуск открыт при φ 139…371°.
 * Единицы: ° фазы φ. Источник: Engine.html:439. Группа: фазы.
 */
export const EX_MID = 255;

/**
 * Опережение зажигания: искра за 10° коленвала до ВМТ. В модели давления сгорание
 * начинается при pc = −SPARK_ADV (функция pClosed, sim/thermo.js).
 * Единицы: ° коленвала. Источник: Engine.html:440. Группа: фазы.
 */
export const SPARK_ADV = 10;

// ---------- Спецификация A: объёмы модели давления, см³ ----------

/**
 * Рабочий объём одного цилиндра π/4 · D² · S из геометрии сцены (1 u = 10 см):
 * π · (BORE_R · 10)² · (2 · CRANK_R · 10) ≈ 408,564 см³. Только умножения, без ** и Math.pow,
 * чтобы результат не зависел от движка. То же выражение — в объявлении const VS в Engine.html
 * (побитное совпадение проверяет spec-sync.test.js).
 * Единицы: см³. Источник: D-05; BORE_R, CRANK_R. Группа: A.
 */
export const VS = Math.PI * (BORE_R * 10) * (BORE_R * 10) * (2 * CRANK_R * 10);

/**
 * Объём камеры сгорания VC = VS / (CR − 1) ≈ 43,007 см³; (VS + VC) / VC = CR = 10,5.
 * CR − 1 = 9,5 точно, поэтому совпадает с выражением VS / 9.5 в Engine.html.
 * Единицы: см³. Источник: D-05; VS, CR. Группа: A, модель давления.
 */
export const VC = VS / (CR - 1);

/**
 * Рабочий объём двигателя: CYLINDERS · VS ≈ 1634,26 см³ (в карточке блока — «1634 см³»).
 * Единицы: см³. Источник: D-05; CYLINDERS, VS. Группа: A.
 */
export const DISPLACEMENT_CM3 = CYLINDERS * VS;
