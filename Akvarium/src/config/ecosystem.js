/**
 * Параметры стилизованных моделей экосистемы (A-04, aquarium-ecosystem → ecosystem-models §6): голод и сытость —
 * HUNGER (§6.1, sim/hunger.js), ночной отдых и укрытия — REST (§6.2, sim/rest.js). Только числа, без кода, three и DOM:
 * их удобно сравнивать и подбирать в одном месте, а тесты читают их в Node. Обе модели — стилизация, а не
 * физиология; в панели это поясняет подпись BEHAVIOR_NOTE (ui/strings.ru.js) под ползунком «Рыбы».
 * Номера камней в REST — индексы OBST в main.js (сферы [x, y, z, радиус], от которых отталкиваются рыбы).
 */
const HUNGER = Object.freeze({
  rate: 1 / 120,      // рост голода, 1/с: от сытости до полного голода за 2 мин
  bite: 0.15,         // голод, который снимает один укус
  sated: 0.2,         // ниже — рыба сыта и не замечает корм
  resume: 0.35,       // выше — снова замечает (гистерезис)
  start: [0.5, 0.9],  // начальный голод, U(a, b) из детерминированного ГПСЧ
  reachMin: 0.5,      // доля радиуса поиска корма у почти сытой рыбы
  boostMin: 0.4,      // доля прибавки скорости к корму у почти сытой рыбы
});

const REST = Object.freeze({
  on: 0.35,           // «Ночь», с которой начинается отдых: день и закат (0,22) не меняются
  act: 0.7,           // активность a = 1 − act·r (§6.2): верхний предел скорости сдвигается к нижнему
  pull: 0.85,         // доля пути точки стаи к укрытию при r = 1 (остаток — дневное блуждание)
  above: 0.9,         // высота укрытия стаи над верхом камня
  school: Object.freeze([0, 3]),   // камни для укрытий стай: хромисы — левый риф, антиасы — правый
  solo: Object.freeze({ tang: Object.freeze([3, 4]), ytang: Object.freeze([0, 1]), idol: Object.freeze([5]) }),   // камни для одиночных рыб
  side: Object.freeze([1.1, 2.04]),   // угол точки у камня, рад: передняя сторона (≈ 0,35π…0,65π)
  gap: 0.9,           // отступ точки от поверхности камня
  sideY: 0.4,         // высота точки над центром камня
  spread: 0.4,        // доля дневного разброса цели клоунов у анемона при r = 1
});

// остатки корма на песке (A-04, шаг 3): пока их не больше cap — прежнее поведение (life с на дне, последние fade с хлопья тают);
// сверх cap самые старые растворяются в rush раз быстрее, чтобы дно не зарастало кормом при частом кормлении
const REMAINS = Object.freeze({ life: 16, fade: 3, cap: 40, rush: 4 });

export { HUNGER, REST, REMAINS };
